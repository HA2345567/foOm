import { chromium } from "playwright";
import { mkdir } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import path from "node:path";

const root = process.cwd();
const output = path.join(root, "target", "ui-preview");
await mkdir(output, { recursive: true });
let browser;
try { browser = await chromium.launch({ channel: "msedge", headless: true }); }
catch { browser = await chromium.launch({ headless: true }); }
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const page = await context.newPage();
page.setDefaultTimeout(120000);
page.setDefaultNavigationTimeout(120000);
const errors = [];
page.on("pageerror", error => errors.push(error.message));
await page.goto("http://localhost:5174", { waitUntil: "domcontentloaded" });
await page.getByText("Your ideas, in motion.").waitFor();
await page.screenshot({ path: path.join(output, "studio-home.png"), fullPage: true });
const clip = path.join(output, "foom-demo.mp4");
const ffmpeg = path.join(root, "apps/desktop/tauri-shell/src-tauri/binaries/ffmpeg-x86_64-pc-windows-msvc.exe");
const result = spawnSync(ffmpeg, ["-y", "-loop", "1", "-i", path.join(output, "studio-home.png"), "-t", "3", "-vf", "scale=1440:1000", "-r", "30", "-pix_fmt", "yuv420p", clip], { windowsHide: true });
if (result.status !== 0) throw new Error(result.stderr?.toString().slice(-1500));
const chooser = page.waitForEvent("filechooser");
await page.getByRole("button", { name: /Give a video a new look/ }).click();
await (await chooser).setFiles(clip);
await page.waitForTimeout(2000);
await page.goto("http://localhost:5174/?windowType=editor", { waitUntil: "domcontentloaded" });
await page.waitForTimeout(4000);
await page.locator(".studio-inspector-content").waitFor({ state: "visible" });
const inspector = await page.locator(".editor-settings-rail").boundingBox();
if (!inspector || inspector.width < 250) throw new Error("Editor inspector collapsed");
await page.waitForFunction(() => document.querySelector("video")?.readyState >= 2 && document.querySelectorAll("canvas").length >= 1);
await page.getByRole("button", { name: "Play", exact: true }).click();
await page.waitForFunction(() => document.querySelector("video")?.currentTime > 0.2);
await page.getByRole("button", { name: "Pause", exact: true }).click();
await page.locator(".studio-export-button").click();
await page.locator(".studio-export-popover").waitFor({ state: "visible" });
await page.keyboard.press("Escape");
await page.screenshot({ path: path.join(output, "studio-editor.png"), fullPage: true });
console.log(JSON.stringify(await page.locator("video").evaluateAll(videos => videos.map(video => ({ src: video.currentSrc, ready: video.readyState, error: video.error?.message, width: video.videoWidth, height: video.videoHeight })))));
await page.goto("http://localhost:5174/#/settings", { waitUntil: "domcontentloaded" });
await page.waitForTimeout(1000);
await page.screenshot({ path: path.join(output, "studio-settings.png"), fullPage: true });
console.log(JSON.stringify({ output, errors }));
await page.goto("http://localhost:5174/?windowType=hud-overlay", { waitUntil: "domcontentloaded" });
const recordButton = page.getByTestId("launch-record-button");
await recordButton.waitFor();
if (!(await recordButton.isEnabled())) throw new Error("First-use recorder button is disabled");
await page.locator("[data-tray-layout]").screenshot({ path: path.join(output, "studio-toolbar.png") });
await browser.close();
